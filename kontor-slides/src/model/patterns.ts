export const PATTERNS: { id: string; label: string }[] = Object.keys(BITS).map((id) => ({ id, label: LABELS[id] ?? id }))

/** SVG path of the foreground cells of a pattern tile. */
export function patternPath(preset: string) {
  const rows = BITS[preset] ?? BITS.pct50
  let d = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < 8; x++) if (row[x] === '#') d += `M${x} ${y}h1v1h-1z`
  })
  return d
}

/** The tile as a data URL (for CSS backgrounds and SVG pattern images); colors as CSS colors. */
export function patternTile(preset: string, fg: string, bg: string, scale = 1) {
  const s = 8 * scale
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 8 8" shape-rendering="crispEdges"><rect width="8" height="8" fill="${bg}"/><path d="${patternPath(preset)}" fill="${fg}"/></svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}
